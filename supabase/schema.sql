-- Derived from how the code actually uses the table:
--   * js/app.js    -> INSERTs a booking row (no `status`, so it needs a default)
--   * admin.html   -> SELECTs rows, UPDATEs `status` / `confirmed_at` /
--                     `notes` / `reminder_sent`, and INSERTs manual bookings
--
-- Both the public site and the admin panel use the anon key.
--
-- This file is IDEMPOTENT: it is safe to run on a fresh project or on the
-- existing one. The `alter table ... add column if not exists` statements below
-- guarantee that columns the app depends on (notably `reminder_sent`) exist even
-- if the table was created earlier without them.
--
-- Run it in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------
create table if not exists public.bookings (
  id            bigint generated by default as identity primary key,
  ref           text        not null,
  name          text        not null,
  phone         text        not null,
  email         text,
  service       text        not null,
  units         integer,
  estimate      numeric,
  months        integer,
  appt_date     date        not null,
  time_slot     text,
  source        text        default 'unknown',
  notes         text,
  status        text        not null default 'pending',
  confirmed_at  timestamptz,
  reminder_sent boolean     not null default false,   -- <-- required by admin Reminders
  created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Column backfill (idempotent) — guarantees these exist on an existing table
-- ---------------------------------------------------------------------------
alter table public.bookings add column if not exists email         text;
alter table public.bookings add column if not exists units         integer;
alter table public.bookings add column if not exists estimate      numeric;
alter table public.bookings add column if not exists months        integer;
alter table public.bookings add column if not exists time_slot     text;
alter table public.bookings add column if not exists source        text default 'unknown';
alter table public.bookings add column if not exists notes         text;
alter table public.bookings add column if not exists status        text not null default 'pending';
alter table public.bookings add column if not exists confirmed_at  timestamptz;
alter table public.bookings add column if not exists reminder_sent boolean not null default false;
alter table public.bookings add column if not exists created_at    timestamptz not null default now();

-- ---------------------------------------------------------------------------
-- Constraints & indexes
-- ---------------------------------------------------------------------------
-- `ref` must be unique: admin.html retries an insert when Postgres raises
-- 23505 (unique_violation), i.e. it regenerates `ref` and tries again.
create unique index if not exists bookings_ref_key
  on public.bookings (ref);

create index if not exists bookings_created_at_idx on public.bookings (created_at desc);
create index if not exists bookings_appt_date_idx  on public.bookings (appt_date);
create index if not exists bookings_status_idx     on public.bookings (status);

-- ---------------------------------------------------------------------------
-- Row Level Security
--
-- SECURITY NOTE: the admin panel (admin.html) talks to Supabase with the
-- public anon key, so the policies below must allow anon SELECT and UPDATE for
-- the panel to work. That also means anyone holding the anon key can read and
-- modify every booking. Before production, move the admin panel behind real
-- auth (Supabase Auth + a `role` claim, or a server-side route using the
-- service role key) and remove the anon SELECT/UPDATE policies below.
-- ---------------------------------------------------------------------------
alter table public.bookings enable row level security;

-- Public booking form may create rows.
drop policy if exists "bookings anon insert" on public.bookings;
create policy "bookings anon insert"
  on public.bookings for insert
  to anon
  with check (true);

-- Admin panel reads rows (see security note above).
drop policy if exists "bookings anon select" on public.bookings;
create policy "bookings anon select"
  on public.bookings for select
  to anon
  using (true);

-- Admin panel updates status / notes / reminder_sent (see security note above).
drop policy if exists "bookings anon update" on public.bookings;
create policy "bookings anon update"
  on public.bookings for update
  to anon
  using (true)
  with check (true);

-- Table privileges for the anon role (identity column needs sequence access).
grant usage on schema public to anon;
grant select, insert, update on public.bookings to anon;
grant usage, select on all sequences in schema public to anon;
